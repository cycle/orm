<?php

declare(strict_types=1);

namespace Cycle\ORM\Tests\Regression\Case8;

use Cycle\ORM\Heap\Heap;
use Cycle\ORM\Select;
use Cycle\ORM\Tests\Regression\Case8\Entity\Event;
use Cycle\Testing\Database\Attribute\OnlyDriver;
use Cycle\Testing\Database\Driver;
use Cycle\Testing\ORM\OrmTestCase;

/**
 * Composite primary key where one part is supplied by the application and the other is generated
 * by the database.
 *
 * # Scenario
 *
 * A partitioning-friendly table:
 *
 *  - `parent_id` — a UUID (UUID7, time-ordered) provided by the application. On the database side
 *    it is the partition key, therefore — by PostgreSQL's rules — it MUST be a part of the primary
 *    key of a partitioned table.
 *  - `id` — generated by the database (`bigserial` / `IDENTITY`). It provides the actual row
 *    uniqueness; `parent_id` only co-locates rows into a partition.
 *
 * The primary key is the composite `(parent_id, id)`. The novelty compared to the other composite
 * PK fixtures (see {@see \Cycle\ORM\Tests\Feature\Common\Schema\CompositePKTest} where
 * every key part is assigned by the application) is that ONE part of the key is produced by the
 * database during the INSERT and has to be read back into the entity.
 *
 * # How the generated key is read back
 *
 * The `id` field is declared as {@see \Cycle\ORM\Schema\GeneratedField::ON_INSERT} in
 * {@see \Cycle\ORM\SchemaInterface::GENERATED_FIELDS} (see `schema.php`). On INSERT the mapper
 * omits that column and asks the database to return its value:
 *
 *  - {@see \Cycle\ORM\Command\Database\Insert::execute()} appends a `RETURNING` clause for every
 *    `ON_INSERT` field and writes the returned value back into the entity state — this path is
 *    independent of how many columns the primary key has.
 *  - The legacy `lastInsertId` path is only used for a SINGLE-column key:
 *    {@see \Cycle\ORM\Mapper\DatabaseMapper::queueCreate()} passes `null` as the pk column when the
 *    key is composite. So for a composite key the generated value can ONLY be obtained via
 *    `RETURNING`.
 *
 * Therefore this case is bound to drivers that implement
 * {@see \Cycle\Database\Query\ReturningInterface} (PostgreSQL, SQL Server, SQLite since
 * cycle/database 2.22). On MySQL the generated `id` of a composite key would not be returned.
 * The case runs on SQLite and PostgreSQL; each needs its own table layout (see the `create*EventTable()`
 * methods), and PostgreSQL also checks a real RANGE-partitioned table.
 *
 * # Mapping gotcha
 *
 * In `schema.php` the keys of {@see \Cycle\ORM\SchemaInterface::PRIMARY_KEY},
 * {@see \Cycle\ORM\SchemaInterface::FIND_BY_KEYS}, {@see \Cycle\ORM\SchemaInterface::TYPECAST} and
 * {@see \Cycle\ORM\SchemaInterface::GENERATED_FIELDS} are FIELD names (the keys of `COLUMNS`),
 * NOT the database column names. Using a column name (`parent_id`) instead of the field
 * (`parentId`) lets INSERTs succeed but breaks reads with `Undefined array key ...` during result
 * parsing, because the parser keys rows by field name.
 *
 * @see Event The mapped entity.
 */
#[OnlyDriver(Driver::SQLite, Driver::Postgres)]
class CaseTest extends OrmTestCase
{
    /** Two UUID7 values sharing the same time prefix — i.e. the same logical "parent" / partition. */
    private const PARENT_A = '0191b6e0-0000-7000-8000-000000000001';

    private const PARENT_B = '0191b6e0-0000-7000-8000-000000000002';

    /** UUID below the partition boundary `8000...` => lands in `event_p0`. */
    private const PARENT_LOW = '01000000-0000-7000-8000-000000000000';

    /** UUID at/above the partition boundary `8000...` => lands in `event_p1`. */
    private const PARENT_HIGH = 'f1000000-0000-7000-8000-000000000000';

    /**
     * A freshly created entity has no `id` (it is `null`); after persisting, the database-generated
     * value of the `id` part of the composite key is read back into the entity via `RETURNING`.
     */
    #[\Testo\Test]
    public function testCreateGeneratesIdFromDatabase(): void
    {
        $event = new Event(self::PARENT_A, 'first');
        \Testo\Assert::null($event->id);

        $this->save($event);

        // The `id` part of the composite PK has been generated by the database and read back.
        \Testo\Assert::int($event->id);
        \Testo\Assert::numeric($event->id)->greaterThan(0);
    }

    /**
     * Two entities sharing the same `parent_id` (the same partition) still receive distinct `id`
     * values — the autoincrement sequence is global to the table, not per-parent, so the composite
     * keys `(parent_id, id)` do not collide.
     */
    #[\Testo\Test]
    public function testSiblingsUnderSameParentGetDistinctIds(): void
    {
        $a = new Event(self::PARENT_A, 'a');
        $b = new Event(self::PARENT_A, 'b');

        $this->save($a, $b);

        \Testo\Assert::int($a->id);
        \Testo\Assert::int($b->id);
        \Testo\Assert::notSame($b->id, $a->id);
    }

    /**
     * After persisting, the row can be loaded back by its full composite key. The heap is reset
     * first so the entity is actually re-read from the database (and not served from the identity
     * map), which also exercises result parsing keyed by field name — the place that breaks if
     * {@see \Cycle\ORM\SchemaInterface::PRIMARY_KEY} lists column names instead of field names.
     *
     * The argument to {@see Select::wherePK()} is ordered to match `PRIMARY_KEY`
     * (`['parentId', 'id']`): `parent_id` first, then `id`.
     */
    #[\Testo\Test]
    public function testFetchByCompositePk(): void
    {
        $event = new Event(self::PARENT_B, 'payload-b');
        $this->save($event);

        // Drop the heap to force a real round-trip to the database.
        $this->orm = $this->orm->withHeap(new Heap());

        $found = (new Select($this->orm, Event::class))
            ->wherePK([self::PARENT_B, $event->id]) // order matches Schema::PRIMARY_KEY
            ->fetchOne();

        \Testo\Assert::instanceOf($found, Event::class);
        \Testo\Assert::same($found->parentId, self::PARENT_B);
        \Testo\Assert::same($found->id, $event->id);
        \Testo\Assert::same($found->payload, 'payload-b');
    }

    /**
     * The whole case (composite PK + database-generated id, fetched via RETURNING) against a real
     * RANGE-partitioned table. `parent_id` (UUID7) is the partition key, therefore it has to be a
     * part of the composite primary key.
     */
    #[\Testo\Test]
    #[OnlyDriver(Driver::Postgres)]
    public function testRowsAreRoutedToPartitions(): void
    {
        $low = new Event(self::PARENT_LOW, 'low');
        $high = new Event(self::PARENT_HIGH, 'high');

        $this->save($low, $high);

        // ids were generated by the database even though the insert targets a partitioned table
        \Testo\Assert::int($low->id);
        \Testo\Assert::int($high->id);

        $db = $this->getDatabase();

        // Each row physically landed in the partition selected by its parent_id.
        \Testo\Assert::same($db->table('event_p0')->select()->where('payload', 'low')->count(), 1);
        \Testo\Assert::same($db->table('event_p0')->select()->where('payload', 'high')->count(), 0);
        \Testo\Assert::same($db->table('event_p1')->select()->where('payload', 'high')->count(), 1);
        \Testo\Assert::same($db->table('event_p1')->select()->where('payload', 'low')->count(), 0);

        // ...and they are both visible through the partitioned parent table.
        \Testo\Assert::same($db->table('event')->select()->count(), 2);
    }

    #[\Testo\Lifecycle\BeforeTest]
    public function setUp(): void
    {
        match ($this->driver) {
            Driver::SQLite => $this->createSQLiteEventTable(),
            Driver::Postgres => $this->createPostgresEventTable(),
        };

        $this->loadSchema(__DIR__ . '/schema.php');
    }

    /**
     * Drop the partitioned table (and its partitions + owned sequence) before the harness's
     * introspection-based cleanup runs, which does not handle partitioned tables.
     */
    #[\Testo\Lifecycle\AfterTest]
    public function dropPartitionedTable(): void
    {
        $this->driver === Driver::Postgres and $this->getDatabase()->execute('DROP TABLE IF EXISTS event CASCADE');
    }

    /**
     * SQLite has no sequences. The only autoincrementing column is the `rowid` alias, and it
     * requires a SINGLE-column `INTEGER PRIMARY KEY`. Inside a real composite
     * `PRIMARY KEY (parent_id, id)` the `id` column is an ordinary one — inserting without it
     * (or with `NULL`) fails with `NOT NULL constraint failed`, and there is nothing for the
     * database to generate. The table therefore keeps `id` as the physical single-column
     * primary key and expresses the logical composite key as `UNIQUE (parent_id, id)`, which
     * doubles as the index serving `wherePK()` lookups. The ORM-side schema is unchanged:
     * `PRIMARY_KEY => ['parentId', 'id']`.
     */
    private function createSQLiteEventTable(): void
    {
        $this->getDatabase()->execute(
            <<<'SQL'
                CREATE TABLE event (
                    parent_id varchar(36) NOT NULL,
                    id        integer     NOT NULL PRIMARY KEY AUTOINCREMENT,
                    payload   varchar(255),
                    UNIQUE (parent_id, id)
                )
                SQL,
        );
    }

    /**
     * RANGE partitioning by the UUID7 partition key. `id` is a bigserial that is part of the
     * composite PK but not the sole key — exactly the scenario discussed for this case.
     */
    private function createPostgresEventTable(): void
    {
        $db = $this->getDatabase();

        $db->execute(
            <<<'SQL'
                CREATE TABLE event (
                    parent_id uuid        NOT NULL,
                    id        bigserial   NOT NULL,
                    payload   varchar(255),
                    PRIMARY KEY (parent_id, id)
                ) PARTITION BY RANGE (parent_id)
                SQL,
        );
        $db->execute(
            "CREATE TABLE event_p0 PARTITION OF event "
            . "FOR VALUES FROM (MINVALUE) TO ('80000000-0000-0000-0000-000000000000')",
        );
        $db->execute(
            "CREATE TABLE event_p1 PARTITION OF event "
            . "FOR VALUES FROM ('80000000-0000-0000-0000-000000000000') TO (MAXVALUE)",
        );
    }
}
