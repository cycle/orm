<?php

declare(strict_types=1);

namespace Cycle\ORM\Tests\Feature\Common;

use Cycle\Database\Injection\Fragment;
use Cycle\Database\Schema\AbstractColumn;
use Cycle\Database\Schema\AbstractTable;
use Cycle\ORM\Command\CommandInterface;
use Cycle\ORM\Mapper\Mapper;
use Cycle\ORM\ORMInterface;
use Cycle\ORM\Schema;
use Cycle\ORM\Schema\GeneratedField;
use Cycle\ORM\SchemaInterface;
use Cycle\ORM\Select;
use Cycle\ORM\Tests\Fixtures\CyclicRef2\Document;
use Cycle\ORM\Tests\Fixtures\User;
use Cycle\ORM\Transaction;
use Cycle\Testing\Database\Attribute\OnlyDriver;
use Cycle\Testing\Database\Driver;
use Cycle\Testing\ORM\OrmFactory;
use Cycle\Testing\ORM\OrmTestCase;
use Ramsey\Uuid\Uuid;
use Testo\Assert;
use Testo\Lifecycle\BeforeTest;
use Testo\Test;

/**
 * Columns generated by the database: a Postgres `serial`, or a SQL Server sequence default.
 */
#[OnlyDriver(Driver::Postgres, Driver::SQLServer)]
final class GeneratedColumnTest extends OrmTestCase
{
    #[Test]
    public function testPersist(): void
    {
        $u = new User();
        $u->id = Uuid::uuid4()->toString();

        $this->save($u);

        Assert::notNull($u->balance);

        $this->orm->getHeap()->clean();

        $s = (new Select($this->orm, User::class))->wherePK($u->id)->fetchOne();

        Assert::same($s->balance, $u->balance);
    }

    #[Test]
    public function testPersistMultipleSerial(): void
    {
        $d1 = new Document();

        $d2 = new Document();
        $d2->body = 213;
        $d2->created_at = $d2->updated_at = new \DateTimeImmutable('2020-01-01');

        $d3 = new Document();
        $d3->created_at = $d3->updated_at = new \DateTimeImmutable('2020-01-01');


        $this->save($d1, $d2, $d3);

        Assert::equals($d1->id, 1);
        Assert::equals($d1->body, 1);
        Assert::notSame($d1->created_at->format('Y-m-d'), '2020-01-01');
        Assert::equals($d2->id, 2);
        Assert::equals($d2->body, 213);
        Assert::same($d2->created_at->format('Y-m-d'), '2020-01-01');
        Assert::equals($d3->id, 3);
        Assert::equals($d3->body, 2);
        Assert::same($d3->created_at->format('Y-m-d'), '2020-01-01');
    }

    #[BeforeTest]
    public function setUp(): void
    {
        $this->createTables();

        $this->orm = (new OrmFactory($this->commandGenerator()))($this->dbal, new Schema([
            User::class => [
                SchemaInterface::ROLE => 'user',
                SchemaInterface::MAPPER => Mapper::class,
                SchemaInterface::DATABASE => 'default',
                SchemaInterface::TABLE => 'user',
                SchemaInterface::PRIMARY_KEY => 'id',
                SchemaInterface::COLUMNS => ['id', 'balance'],
                SchemaInterface::SCHEMA => [],
                SchemaInterface::RELATIONS => [],
                SchemaInterface::GENERATED_FIELDS => [
                    'balance' => GeneratedField::ON_INSERT, // sequence
                ],
            ],
            Document::class => [
                SchemaInterface::ROLE => 'profile',
                SchemaInterface::MAPPER => Mapper::class,
                SchemaInterface::DATABASE => 'default',
                SchemaInterface::TABLE => 'document',
                SchemaInterface::PRIMARY_KEY => 'id',
                SchemaInterface::COLUMNS => ['id', 'body', 'created_at', 'updated_at'],
                SchemaInterface::SCHEMA => [],
                SchemaInterface::RELATIONS => [],
                SchemaInterface::TYPECAST => [
                    'created_at' => 'datetime',
                    'updated_at' => 'datetime',
                ],
                SchemaInterface::GENERATED_FIELDS => [
                    'id' => GeneratedField::ON_INSERT,
                    'body' => GeneratedField::ON_INSERT,
                    'created_at' => GeneratedField::ON_INSERT,
                    'updated_at' => GeneratedField::BEFORE_INSERT | GeneratedField::BEFORE_UPDATE,
                ],
            ],
        ]));
    }

    private function createTables(): void
    {
        if ($this->driver === Driver::SQLServer) {
            foreach (['testSequence1', 'testSequence2'] as $sequence) {
                $this->getDatabase()->query("DROP SEQUENCE IF EXISTS {$sequence};");
                $this->getDatabase()->query("CREATE SEQUENCE {$sequence} START WITH 1;");
            }
        }

        $schema = $this->getDatabase()->table('user')->getSchema();
        $schema->column('id')->type('uuid');
        $this->declareGenerated($schema, 'balance', 'testSequence1');
        $schema->save();

        $this->getDatabase()->table('user')->insertMultiple(
            ['id'],
            [
                [Uuid::uuid4()->toString()],
                [Uuid::uuid4()->toString()],
                [Uuid::uuid4()->toString()],
            ],
        );

        $schema = $this->getDatabase()->table('document')->getSchema();
        $schema->column('id')->primary();
        $this->declareGenerated($schema, 'body', 'testSequence2');
        $schema->column('created_at')->type('datetime')->nullable(false)->defaultValue(AbstractColumn::DATETIME_NOW);
        $schema->column('updated_at')->type('datetime')->nullable(false);
        $schema->save();
    }

    private function declareGenerated(AbstractTable $schema, string $column, string $sequence): void
    {
        if ($this->driver === Driver::Postgres) {
            $schema->column($column)->type('serial')->nullable(false);
            return;
        }

        $schema->column($column)->type('int')->nullable(false)
            ->defaultValue(new Fragment("NEXT VALUE FOR {$sequence}"));
    }

    private function commandGenerator(): Transaction\CommandGeneratorInterface
    {
        return new class extends Transaction\CommandGenerator {
            protected function storeEntity(ORMInterface $orm, Transaction\Tuple $tuple, bool $isNew): ?CommandInterface
            {
                /** @var CommandInterface|null $command */
                $command = parent::storeEntity($orm, $tuple, $isNew);

                if ($command !== null && $tuple->entity instanceof Document && empty($tuple->entity->updated_at)) {
                    $now = new \DateTimeImmutable();
                    $tuple->state->register('updated_at', $now);
                    $tuple->entity->updated_at = $now;
                }

                return $command;
            }
        };
    }
}
